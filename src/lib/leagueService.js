import { addDoc, collection, doc, getDocs, serverTimestamp, updateDoc, writeBatch } from "firebase/firestore";
import { db } from "../firebase";
import { generateFixtures, matchResult, MAX_BATCH_WRITES, validatePlayerName } from "./league.js";

const read = async (name) => (await getDocs(collection(db, name))).docs.map((item) => ({ ...item.data(), id: item.id }));

async function commit(operations) {
  if (operations.length > MAX_BATCH_WRITES) throw new Error("Too many related records for one atomic operation. No records were changed. Contact the league administrator.");
  if (!operations.length) return;
  const batch = writeBatch(db);
  operations.forEach(([method, path, data]) => {
    const ref = doc(db, ...path);
    if (method === "delete") batch.delete(ref);
    else batch[method](ref, data);
  });
  await batch.commit();
}

export async function createPlayer(value) {
  const name = validatePlayerName(value, await read("players"));
  await addDoc(collection(db, "players"), { name });
}

export async function renamePlayer(playerId, value) {
  const [players, matches] = await Promise.all([read("players"), read("matches")]);
  const player = players.find((item) => item.id === playerId);
  if (!player) throw new Error("This player no longer exists. Reload and try again.");
  const name = validatePlayerName(value, players, playerId);
  if (name === player.name) return;
  const operations = matches.filter((m) => m.homeTeam === player.name || m.awayTeam === player.name)
    .map((match) => ["update", ["matches", match.id], {
      homeTeam: match.homeTeam === player.name ? name : match.homeTeam,
      awayTeam: match.awayTeam === player.name ? name : match.awayTeam,
    }]);
  await commit([["update", ["players", playerId], { name }], ...operations]);
}

export async function removePlayer(playerId) {
  const [players, matches] = await Promise.all([read("players"), read("matches")]);
  const player = players.find((item) => item.id === playerId);
  if (!player) throw new Error("This player no longer exists. Reload and try again.");
  const operations = matches.filter((m) => m.homeTeam === player.name || m.awayTeam === player.name)
    .map((match) => ["delete", ["matches", match.id]]);
  await commit([...operations, ["delete", ["players", playerId]]]);
}

export async function createMatch(homeTeam, awayTeam) {
  const players = await read("players");
  if (!homeTeam || !awayTeam || homeTeam === awayTeam) throw new Error("Choose two different players.");
  if (![homeTeam, awayTeam].every((name) => players.some((player) => player.name === name))) throw new Error("A selected player no longer exists. Select the players again.");
  await addDoc(collection(db, "matches"), {
    homeTeam, awayTeam, scoreHome: null, scoreAway: null, status: "Upcoming", autoGenerated: false, createdAt: serverTimestamp(),
  });
}

export async function saveMatch(id, homeScore, awayScore, status) {
  if (!id) throw new Error("Select a match first.");
  await updateDoc(doc(db, "matches", id), {
    ...matchResult(homeScore, awayScore, status), completedAt: status === "Finished" ? serverTimestamp() : null,
  });
}

export async function createLeague() {
  const [players, matches] = await Promise.all([read("players"), read("matches")]);
  if (matches.length) throw new Error("The league already has matches. Clear the current league before generating fixtures.");
  const fixtures = generateFixtures(players);
  await commit(fixtures.map((fixture) => ["set", ["matches", doc(collection(db, "matches")).id], {
    ...fixture, scoreHome: null, scoreAway: null, status: "Upcoming", autoGenerated: true, createdAt: serverTimestamp(),
  }]));
}

export async function clearLeague() {
  await commit((await read("matches")).map((match) => ["delete", ["matches", match.id]]));
}
